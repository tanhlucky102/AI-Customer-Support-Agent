"""One command to prepare the whole demo (run from the repository root):

    python scripts/setup_demo.py               # no AI Box calls needed
    python scripts/setup_demo.py --contextual  # also write LLM context sentences for every chunk

It is idempotent. Steps:
  1. create missing secrets in .env (shared by the Agent Server and the demo websites);
  2. seed the demo shop's SQLite data if empty;
  3. register three shops, one per integration level:
       sample_store  level 0  content only (pushed FAQ), no commerce API
       demo_shop     level 1  commerce API implementing contract C2 ("standard" profile)
       second_shop   level 1  its own foreign API, read through examples/second_shop/commerce.json
  4. index the knowledge bases (data/kb/<shop>) and the sample store's FAQ;
  5. publish the demo shop's promotions/events snapshot.
"""

import argparse
import asyncio
import json
import os
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
ENV = ROOT / ".env"
SECRETS = ("DEMO_SHOP_API_KEY", "DEMO_SHOP_TOKEN_SECRET", "DEMO_SHOP_SESSION_SECRET",
           "DEMO_FAQ_WRITE_KEY", "SECOND_SHOP_API_KEY", "SECOND_SHOP_TOKEN_SECRET",
           "SECOND_SHOP_WRITE_KEY", "SECOND_SHOP_SESSION_SECRET", "SAMPLE_STORE_TOKEN_SECRET",
           "SAMPLE_STORE_WRITE_KEY")


def ensure_env() -> list[str]:
    text = ENV.read_text(encoding="utf-8") if ENV.exists() else ""
    present = {line.split("=", 1)[0].strip() for line in text.splitlines()
               if "=" in line and not line.lstrip().startswith("#") and line.split("=", 1)[1].strip()}
    added = [name for name in SECRETS if name not in present]
    extra = {"SECOND_SHOP_PUBLIC_KEY": "pk_second_shop"}
    added_extra = [name for name in extra if name not in present]
    if added or added_extra:
        lines = ["", "# Generated by scripts/setup_demo.py"]
        lines += [f"{name}={secrets.token_urlsafe(32)}" for name in added]
        lines += [f"{name}={extra[name]}" for name in added_extra]
        with ENV.open("a", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
    return added + added_extra


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--contextual", action="store_true", help="Contextual Retrieval (off by default)")
    args = parser.parse_args()

    added = ensure_env()
    print("secrets added to .env:", added or "none")

    # Imported only now, so the settings module reads the completed .env.
    from agent_server import store
    from rag.ingest import index_faqs, ingest_dir
    from shared.llm import LLMProvider
    from shared.settings import env

    seeded = subprocess.run([sys.executable, "seed.py"], cwd=ROOT / "shop_demo", capture_output=True,
                            env={**os.environ, "PYTHONUTF8": "1"},
                            text=True, encoding="utf-8")
    print("demo shop data:", (seeded.stdout or seeded.stderr).strip().splitlines()[-1:])

    store.init_db()
    config = json.loads((ROOT / "examples" / "second_shop" / "commerce.json").read_text(encoding="utf-8"))
    config["base_url"] = env("SECOND_SHOP_API_URL", config["base_url"])  # e.g. Docker service name
    second_url = env("SECOND_SHOP_URL", "http://localhost:8003")
    second_origins = ["http://localhost:8003", "http://127.0.0.1:8003"]
    sample_origins = ["http://localhost:8002", "http://127.0.0.1:8002"]
    if store.shop_by_id("second_shop"):  # Re-running after .env changes keeps keys in sync.
        store.refresh_shop("second_shop", faq_write_key=env("SECOND_SHOP_WRITE_KEY"),
                           chat_token_secret=env("SECOND_SHOP_TOKEN_SECRET"), shop_url=second_url,
                           allowed_origins=second_origins, commerce_config=config,
                           commerce_api_key=env("SECOND_SHOP_API_KEY"))
    else:
        store.create_shop(
            shop_id="second_shop", public_key=env("SECOND_SHOP_PUBLIC_KEY"),
            faq_write_key=env("SECOND_SHOP_WRITE_KEY"), title="Trợ lý Phụ Kiện Xanh",
            greeting="Chào bạn! Mình là trợ lý của Phụ Kiện Xanh. Bạn cần hỗ trợ gì?",
            primary_color="#0f7a5c", shop_url=second_url, allowed_origins=second_origins,
            chat_token_secret=env("SECOND_SHOP_TOKEN_SECRET"), tone="thân thiện, ngắn gọn",
            suggestions=["Đơn hàng của tôi", "Đổi trả trong bao lâu?", "Phí giao hàng?"],
            commerce_config=config, commerce_api_key=env("SECOND_SHOP_API_KEY"))
    if store.shop_by_id("sample_store"):
        store.refresh_shop("sample_store", faq_write_key=env("SAMPLE_STORE_WRITE_KEY"),
                           chat_token_secret=env("SAMPLE_STORE_TOKEN_SECRET"),
                           shop_url="http://localhost:8002", allowed_origins=sample_origins)
    else:
        store.create_shop(
            shop_id="sample_store", public_key="pk_sample_store", faq_write_key=env("SAMPLE_STORE_WRITE_KEY"),
            title="Trợ lý Sample Store", greeting="Xin chào! Tôi có thể giúp gì cho bạn?",
            primary_color="#334155", shop_url="http://localhost:8002", allowed_origins=sample_origins,
            chat_token_secret=env("SAMPLE_STORE_TOKEN_SECRET"),
            suggestions=["Giờ mở cửa?", "Làm sao liên hệ hỗ trợ?"])
    print("shops:", [(shop, "level 1" if (store.shop_by_id(shop) or {}).get("commerce_config") else "level 0")
                     for shop in ("demo_shop", "second_shop", "sample_store")])

    contextual = args.contextual and LLMProvider().enabled
    for shop_id in ("demo_shop", "second_shop"):
        shop = store.shop_by_id(shop_id)
        stats = asyncio.run(ingest_dir(shop_id, shop["shop_url"], ROOT / "data" / "kb" / shop_id,
                                       contextual=contextual))
        print(f"knowledge base {shop_id}:", stats)
    faqs = json.loads((ROOT / "examples" / "third_party_site" / "faqs.json").read_text(encoding="utf-8"))["faqs"]
    store.replace_faqs("sample_store", faqs)
    print("sample_store FAQ:", asyncio.run(index_faqs("sample_store", "http://localhost:8002", faqs)))

    sys.path.insert(0, str(ROOT / "shop_demo"))
    from sync_assistant import snapshot
    offers = snapshot()["offers"]
    print("demo_shop offers:", store.replace_offers("demo_shop", offers))


if __name__ == "__main__":
    main()
